"""Generate the server and Qt copies of the single OpenAPI v1 contract."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/api/sync-v1.openapi.json"
SERVER = ROOT / "server/internal/protocol/sync-v1.openapi.json"
QT = ROOT / "src/sync/SchemaDefinitions.h"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = SOURCE.read_bytes()
    schemas = json.loads(source)["components"]["schemas"]
    if args.check:
        assert SERVER.read_bytes() == source, "server OpenAPI copy drifted"
        chunks = re.findall(r'R"DMSCHEMA\((.*?)\)DMSCHEMA"', QT.read_text(encoding="utf-8"), re.S)
        assert chunks and json.loads("".join(chunks)) == schemas, "Qt schemas drifted"
        print(f"PASS: server/Qt contract copies match {len(schemas)} schemas")
        return
    encoded = json.dumps(schemas, ensure_ascii=True, separators=(",", ":"))
    assert ')DMSCHEMA"' not in encoded
    # MSVC limits individual string tokens; do not concatenate into one token.
    lines = ["#pragma once", "#include <QByteArray>", "namespace daymark::sync {",
             "// Generated by scripts/generate-sync-contract.py; do not edit.",
             "inline QByteArray schemaDefinitions() {", "    QByteArray bytes;"]
    for start in range(0, len(encoded), 4000):
        lines.append('    bytes.append(R"DMSCHEMA(' + encoded[start:start + 4000] + ')DMSCHEMA");')
    lines += ["    return bytes;", "}", "} // namespace daymark::sync", ""]
    SERVER.write_bytes(source)
    QT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
